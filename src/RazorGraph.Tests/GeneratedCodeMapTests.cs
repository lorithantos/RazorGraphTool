namespace RazorGraph.Tests;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using RazorGraph.Extractor.Roslyn;
using Xunit;

/// <summary>
/// Which .razor or .cshtml file a generated class without [RazorCompiledItem]
/// -- a Blazor component's -- was compiled from. The trees are shaped like the
/// Razor generator's output for tests\fixtures\SampleApp\Components: a
/// #pragma checksum naming the compiled file on the first line, and a #line
/// directive per piece of C# naming the file it came from, the @using and
/// @inject lines of _Imports.razor among them.
/// </summary>
public class GeneratedCodeMapTests
{
    private const string Dir = @"C:\app\Components\";

    private static string Checksum(string file) =>
        $"#pragma checksum \"{Dir}{file}\" \"{{8829d00f-11b8-4213-878b-770e8597ac16}}\" \"00\"\n";

    private static string Line(string file, string code) =>
        $"#line (1,1)-(1,9) \"{Dir}{file}\"\n{code}\n#line default\n#line hidden\n";

    /// <summary>A generated component class: its head, then its body lines.</summary>
    private static SyntaxTree Generated(string className, string head, params string[] body) =>
        CSharpSyntaxTree.ParseText(
            head
            + "// <auto-generated/>\nnamespace App.Components\n{\n"
            + Line("_Imports.razor", "using System.Text;")
            + $"    public partial class {className}\n    {{\n"
            + string.Concat(body)
            + "    }\n}\n",
            path: $@"C:\app\obj\gen\{className}_razor.g.cs");

    private static string? SourceOf(SyntaxTree tree, string className)
    {
        var compilation = CSharpCompilation.Create(
            "Fx",
            [tree],
            [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        var symbol = compilation.GetTypeByMetadataName($"App.Components.{className}")
            ?? throw new InvalidOperationException($"Fixture type not found: {className}");
        return GeneratedCodeMap.GeneratedSourcePath(symbol, [], @"C:\app\App.csproj", tree);
    }

    private static readonly string ImportsInject =
        "private\n" + Line("_Imports.razor", "System.Text.StringBuilder") + Line("_Imports.razor", "Builder") + "{ get; set; }\n";

    /// <summary>
    /// GreetingBadge's shape: markup only, so every #line in its class names
    /// _Imports.razor. The checksum names the badge, and that is the answer.
    /// </summary>
    [Fact]
    public void MarkupOnlyComponent_IsJoinedToItsOwnFile_NotTheImports()
    {
        var tree = Generated("GreetingBadge", Checksum("GreetingBadge.razor"), ImportsInject);

        Assert.Equal(Dir + "GreetingBadge.razor", SourceOf(tree, "GreetingBadge"));
    }

    /// <summary>
    /// GreetingPanel's shape: an @code block, so its own file holds the
    /// majority of the #line directives -- joined as it always was, whether
    /// the checksum or the vote answers.
    /// </summary>
    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void ComponentWithCode_IsJoinedToItsOwnFile(bool withChecksum)
    {
        var code = Line("GreetingPanel.razor", "private string message = \"\";")
            + Line("GreetingPanel.razor", "protected void OnInit() { }");
        var tree = Generated("GreetingPanel", withChecksum ? Checksum("GreetingPanel.razor") : "", ImportsInject, code);

        Assert.Equal(Dir + "GreetingPanel.razor", SourceOf(tree, "GreetingPanel"));
    }

    /// <summary>
    /// Without a checksum, the imports file's lines still do not outvote the
    /// component's own: three _Imports.razor lines against two of its own, and
    /// the component wins. With the imports file in the vote this read
    /// _Imports.razor.
    /// </summary>
    [Fact]
    public void Vote_GivesTheImportsFileNoVote_ForAnotherClass()
    {
        var tree = Generated("Card", "", ImportsInject, Line("Card.razor", "int a;"), Line("Card.razor", "int b;"));

        Assert.Equal(Dir + "Card.razor", SourceOf(tree, "Card"));
    }

    /// <summary>
    /// A markup-only component with no checksum leaves nothing but imports
    /// lines to vote on, and stays unlinked: null, not the imports file and not
    /// a guess.
    /// </summary>
    [Fact]
    public void MarkupOnlyComponent_WithoutChecksum_StaysUnlinked()
    {
        var tree = Generated("GreetingBadge", "", ImportsInject);

        Assert.Null(SourceOf(tree, "GreetingBadge"));
    }

    /// <summary>
    /// _Imports.razor compiles to a class of its own, _Imports, and that class
    /// is still joined to it -- by the checksum, and by the vote without one.
    /// </summary>
    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void ImportsClass_IsJoinedToTheImportsFile(bool withChecksum)
    {
        var tree = Generated("_Imports", withChecksum ? Checksum("_Imports.razor") : "", ImportsInject);

        Assert.Equal(Dir + "_Imports.razor", SourceOf(tree, "_Imports"));
    }

    /// <summary>
    /// A .cshtml imports class is named after its folder and file
    /// (Pages__ViewImports); the vote still counts its own file for it.
    /// Unreached in a real build, where [RazorCompiledItem] answers first.
    /// </summary>
    [Fact]
    public void Vote_CountsViewImports_ForItsOwnMangledClass()
    {
        var tree = CSharpSyntaxTree.ParseText(
            Line("_ViewImports.cshtml", "using System;") + "class Pages__ViewImports { }\n");

        Assert.EndsWith("_ViewImports.cshtml", GeneratedCodeMap.MappedSourcePath(tree, "Pages__ViewImports"));
        Assert.Null(GeneratedCodeMap.MappedSourcePath(tree, "Pages_Shared__Card"));
    }

    /// <summary>
    /// A checksum is only taken when the head names exactly one Razor file:
    /// two make it ambiguous and a non-Razor one (a XAML file's) is not this
    /// generator's, so both fall to the vote -- here, imports lines only, so
    /// unlinked.
    /// </summary>
    [Theory]
    [InlineData("A.razor", "B.razor")]
    [InlineData("MainWindow.xaml", null)]
    public void Checksum_NamingNoSingleRazorFile_IsNotTaken(string first, string? second)
    {
        var head = Checksum(first) + (second == null ? "" : Checksum(second));
        var tree = Generated("GreetingBadge", head, ImportsInject);

        Assert.Null(GeneratedCodeMap.ChecksumSourcePath(tree));
        Assert.Null(SourceOf(tree, "GreetingBadge"));
    }
}
